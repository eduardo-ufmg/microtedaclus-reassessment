"""Tables and figure of the validation of the ported generators.

Written under monografia/Modernization/artifacts/generators/ from the files of
`benchmark.validation.generators` and, for the reproduction across machines,
from the replay of the previous experiment (cross_machine_check.py there).

Usage (from experimentos/modern_methodology):
    python -m benchmark.validation.artifacts
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from benchmark.validation.generators import DESCRIPTORS, OUT_DIR, WINDOW, compare
from pfc_shared.latex import marked, panel_table, write_table

ROOT = Path(__file__).resolve().parents[2]
ARTIFACT_DIR = (
    ROOT.parent.parent / "monografia" / "Modernization" / "artifacts" / "generators"
)
REPLAY_FILE = (
    ROOT.parent / "proposed_methodology" / "metrics" / "cross_machine" / "replay.csv"
)

SHORT_NAMES = {
    "benchmark_1": "B1",
    "benchmark_2": "B2",
    "random_rbf_events": "RBF",
    "cassini": "CSN",
    "chameleon_ds3": "DS3",
    "chameleon_ds4": "DS4",
    **{f"SCL-{d}": f"S{d}" for d in (1, 2, 4, 8, 16, 32, 64)},
}
DATASETS = ["benchmark_1", "benchmark_2", "random_rbf_events", "cassini"]
DESCRIPTOR_TITLES = {
    "clusters": "Clusters present",
    "noise": "Share of noise",
    "spread": "Spread of a cluster",
    "displacement": "Displacement of a cluster between windows",
    "separation": "Smallest distance between clusters",
}
SOURCE_NAMES = {"R": "R", "port": "port", "port, own labels": "port, own labels"}
SOURCE_COLORS = {"R": "xkcd:blue", "port": "xkcd:orange"}


def columns(datasets):
    return {d: SHORT_NAMES[d] for d in datasets}


def comparison_rows(tests, medians_of, row_label, fmt):
    """Rows of R and of the port for one quantity; the port is marked where it differs."""
    reference = {
        d: medians_of(d, "reference_median") for d in tests["dataset"].unique()
    }
    port = {d: medians_of(d, "port_median") for d in tests["dataset"].unique()}
    different = tests.set_index("dataset")["different"].to_dict()

    rows = [(f"{row_label}R", reference, fmt)]
    marked_port = {
        d: marked(fmt(port[d]), "worse" if different[d] else "same") for d in port
    }
    rows.append((f"{row_label}port", marked_port, str))
    return rows


def descriptor_table():
    tests = pd.read_csv(OUT_DIR / "descriptor_tests.csv")
    streams = (
        pd.read_csv(OUT_DIR / "descriptors_by_run.csv")
        .groupby("source")["run"]
        .nunique()["R"]
    )
    panels = []
    for descriptor in DESCRIPTORS:
        of_descriptor = tests[tests.quantity == descriptor]
        lookup = of_descriptor.set_index("dataset")
        fmt = "{:.2f}".format if descriptor == "clusters" else "{:.3f}".format
        panels.append(
            (
                DESCRIPTOR_TITLES[descriptor],
                comparison_rows(of_descriptor, lambda d, c: lookup.loc[d, c], "", fmt),
            )
        )
    panel_table(
        ARTIFACT_DIR / "descriptors.tex",
        f"Structure of the streams generated by R and by the port: medians over {streams} streams of the "
        f"means over windows of {WINDOW} samples. A value in red is significantly different from that of R.",
        "tab:mod_generators_descriptors",
        columns(DATASETS),
        panels,
        first_column="Source",
    )


def behaviour_table():
    tests = pd.read_csv(OUT_DIR / "behaviour_tests.csv")
    titles = {"ari_overall": "Overall ARI", "ari_steadystate": "Steady-State ARI"}
    panels = []
    for quantity, title in titles.items():
        rows = []
        for model in tests["model"].unique():
            of_model = tests[(tests.quantity == quantity) & (tests.model == model)]
            lookup = of_model.set_index("dataset")
            rows += comparison_rows(
                of_model, lambda d, c: lookup.loc[d, c], f"{model}, ", "{:.3f}".format
            )
        panels.append((title, rows))
    panel_table(
        ARTIFACT_DIR / "behaviour.tex",
        "Models with fixed hyperparameters on the streams generated by R and by the port: medians over "
        "the streams. A value in red is significantly different from that of R.",
        "tab:mod_generators_behaviour",
        columns(DATASETS),
        panels,
        first_column="Model and source",
    )


def distribution_table():
    tests = pd.read_csv(OUT_DIR / "distribution_tests.csv")
    datasets = [d for d in DATASETS if d in set(tests["dataset"])]
    coordinates = tests[tests.test != "cluster proportions"].groupby("dataset")
    proportions = tests[tests.test == "cluster proportions"].set_index("dataset")
    rows = [
        (
            "Samples of each source",
            tests.groupby("dataset")["samples"].first(),
            "{:.0f}".format,
        ),
        ("Tests on the coordinates", coordinates.size(), "{:.0f}".format),
        (
            "Largest Kolmogorov-Smirnov statistic",
            coordinates["statistic"].max(),
            "{:.4f}".format,
        ),
        (
            "Smallest adjusted $p$-value of the coordinates",
            coordinates["p_adj"].min(),
            "{:.2f}".format,
        ),
        (
            "Adjusted $p$-value of the cluster proportions",
            proportions["p_adj"],
            "{:.2f}".format,
        ),
    ]
    lines = [
        "Quantity & " + " & ".join(SHORT_NAMES[d] for d in datasets) + r" \\",
        r"\midrule",
    ]
    for label, values, fmt in rows:
        lines.append(" & ".join([label, *(fmt(values[d]) for d in datasets)]) + r" \\")
    write_table(
        ARTIFACT_DIR / "distribution.tex",
        "Two-sample tests between the samples generated by R and by the port, pooled over the streams: "
        "Kolmogorov-Smirnov tests on each coordinate of each cluster and a chi-squared test on the "
        "cluster proportions.",
        "tab:mod_generators_distribution",
        "l " + "c " * len(datasets),
        lines,
    )


def rbf_noise_table():
    noise = pd.read_csv(OUT_DIR / "rbf_noise_by_block.csv")
    medians = noise.groupby(["source", "block"])["noise"].median().unstack()
    names = {
        "R": "R",
        "port": "port, labels of the R wrapper",
        "port, own labels": "port",
    }
    lines = [
        "Source & " + " & ".join(str(block + 1) for block in medians.columns) + r" \\",
        r"\midrule",
    ]
    for source, name in names.items():
        lines.append(
            " & ".join([name, *(f"{v:.2f}" for v in medians.loc[source])]) + r" \\"
        )
    write_table(
        ARTIFACT_DIR / "rbf_noise.tex",
        "Share of the samples of the Random RBF stream that carry the noise label, in consecutive blocks "
        "of 1000 samples: medians over the streams.",
        "tab:mod_generators_rbf_noise",
        "l " + "c " * len(medians.columns),
        lines,
    )


def replay_tables():
    """Stored results of the previous experiment against their replay on regenerated streams."""
    replay = pd.read_csv(REPLAY_FILE)
    runs = replay["run"].nunique()
    datasets = [d for d in SHORT_NAMES if d in set(replay["dataset"])]
    benchmarks = [m for m in replay["model"].unique() if m != "MicroTEDAClusPlus"]
    plus = (
        replay[replay.model == "MicroTEDAClusPlus"]
        .groupby("dataset")["reproduced"]
        .sum()
    )
    together = (
        replay[replay.model.isin(benchmarks)]
        .groupby(["dataset", "run"])["reproduced"]
        .all()
        .groupby("dataset")
        .sum()
    )
    lines = [
        "Models & " + " & ".join(SHORT_NAMES[d] for d in datasets) + r" \\",
        r"\midrule",
        " & ".join([r"\MicroTEDAClusPlus", *(f"{plus[d]:.0f}" for d in datasets)])
        + r" \\",
        " & ".join(
            [
                ", ".join(rf"\modelname{{{m}}}" for m in benchmarks),
                *(f"{together[d]:.0f}" for d in datasets),
            ]
        )
        + r" \\",
    ]
    write_table(
        ARTIFACT_DIR / "replay.tex",
        f"Runs of the main experiment, of {runs} per dataset, whose ARI at every batch is reproduced when "
        "the model is executed again, with the stored hyperparameters, on a stream generated from the "
        "same seed. For the three benchmark models, a run counts when the three reproduce.",
        "tab:mod_generators_replay",
        "l " + "c " * len(datasets),
        lines,
    )

    # Where the streams differ, are they realizations of the same process?
    differing = [d for d in datasets if together[d] < runs]
    stored = replay[replay.model.isin(benchmarks) & replay.dataset.isin(differing)]
    long = pd.concat(
        [
            stored.assign(source="R").rename(
                columns={
                    "stored_ari_overall": "ari_overall",
                    "stored_ari_steadystate": "ari_steadystate",
                }
            ),
            stored.assign(source="port").rename(
                columns={
                    "replayed_ari_overall": "ari_overall",
                    "replayed_ari_steadystate": "ari_steadystate",
                }
            ),
        ]
    )
    tests = compare(long, ["ari_overall", "ari_steadystate"], ["dataset", "model"])
    panels = []
    for quantity, title in {
        "ari_overall": "Overall ARI",
        "ari_steadystate": "Steady-State ARI",
    }.items():
        rows = []
        for model in benchmarks:
            lookup = tests[
                (tests.quantity == quantity) & (tests.model == model)
            ].set_index("dataset")
            rows.append(
                (
                    rf"\modelname{{{model}}}, stored",
                    lookup["reference_median"],
                    "{:.3f}".format,
                )
            )
            replayed = {
                d: marked(
                    f"{lookup.loc[d, 'port_median']:.3f}",
                    "worse" if lookup.loc[d, "different"] else "same",
                )
                for d in lookup.index
            }
            rows.append((rf"\modelname{{{model}}}, replayed", replayed, str))
        panels.append((title, rows))
    panel_table(
        ARTIFACT_DIR / "replay_distribution.tex",
        "Stored results of three benchmark models against their replay on streams generated again from "
        f"the same seeds, in the datasets whose runs are not reproduced: medians over the {runs} runs. A "
        "value in red is significantly different from the stored one.",
        "tab:mod_generators_replay_distribution",
        columns(differing),
        panels,
        first_column="Model and result",
    )


def descriptor_figure():
    """Descriptors along the stream, for the three streams that change over time."""
    windows = pd.read_csv(OUT_DIR / "descriptors_by_window.csv")
    datasets = ["benchmark_1", "benchmark_2", "random_rbf_events"]
    shown = ["clusters", "spread", "displacement", "separation"]
    fig, axes = plt.subplots(len(datasets), len(shown), figsize=(15, 8), sharex="row")
    for row, dataset in enumerate(datasets):
        for column, descriptor in enumerate(shown):
            ax = axes[row, column]
            for source, color in SOURCE_COLORS.items():
                data = windows[
                    (windows.dataset == dataset) & (windows.source == source)
                ]
                bands = (
                    data.groupby("window")[descriptor]
                    .quantile([0.25, 0.5, 0.75])
                    .unstack()
                )
                samples = (bands.index + 1) * WINDOW
                ax.plot(samples, bands[0.5], color=color, linewidth=1.5, label=source)
                ax.fill_between(
                    samples, bands[0.25], bands[0.75], color=color, alpha=0.15
                )
            if row == 0:
                ax.set_title(DESCRIPTOR_TITLES[descriptor], fontsize=10)
            if column == 0:
                ax.set_ylabel(SHORT_NAMES[dataset])
            if row == len(datasets) - 1:
                ax.set_xlabel("Samples")
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2, bbox_to_anchor=(0.5, 1.03))
    plt.tight_layout(rect=(0, 0, 1, 0.97))
    out = ARTIFACT_DIR / "plots" / "descriptors.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=300, bbox_inches="tight")
    plt.close(fig)


def main():
    distribution_table()
    descriptor_table()
    behaviour_table()
    rbf_noise_table()
    descriptor_figure()
    if REPLAY_FILE.exists():
        replay_tables()
    else:
        print("replay of the previous experiment not found: its tables are skipped")


if __name__ == "__main__":
    main()
